CREATE TABLE RATINGS(
RATING_ID INT PRIMARY KEY,
RATING FLOAT CHECK (RATING BETWEEN 1 AND 5),
USER_ID INT,
MOVIE_ID INT,
RATING_DATE DATE,
FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
FOREIGN KEY (MOVIE_ID) REFERENCES MOVIES (MOVIE_ID)


);

