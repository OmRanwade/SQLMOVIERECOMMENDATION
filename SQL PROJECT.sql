SELECT MOVIES.TITLE ,AVG(RATINGS.RATING) AS AVG_RATINGS
FROM RATINGS
JOIN MOVIES ON RATINGS.MOVIE_ID=MOVIES.MOVIE_ID
GROUP BY MOVIES.TITLE
ORDER BY AVG_RATINGS DESC;

CREATE TABLE MOVIE_GENRE(
